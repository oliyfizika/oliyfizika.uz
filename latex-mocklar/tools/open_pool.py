def r(x, nd=3):
    """Javobni nd ta o‘nlik xonagacha yaxlitlab, vergulli matnga aylantirish."""
    x = round(x, nd)
    if abs(x - round(x)) < 1e-9: x = int(round(x))
    return num(x)

def P(st, qa, aa, qb, ab, fig=None):
    return (st, [(qa, aa if isinstance(aa, str) else r(aa)), (qb, ab if isinstance(ab, str) else r(ab))], fig)

